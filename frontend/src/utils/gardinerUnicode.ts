/** Model classes with no glyph: structural tokens, not signs. */
export const NON_SIGN_TOKENS = new Set(["cartouche", "unknown", "Unknown"]);

/**
 * Resolve a pipeline code (any case: "m17", "M17", "Aa1") to its
 * hieroglyph, or null for cartouche/unknown/unmapped codes.
 */
export const toHieroglyph = (code: string): string | null => {
  if (NON_SIGN_TOKENS.has(code)) return null;
  return (
    GARDINER_TO_UNICODE[code] ??
    GARDINER_TO_UNICODE[code.toLowerCase()] ??
    GARDINER_TO_UNICODE[
      code.charAt(0).toUpperCase() + code.slice(1).toLowerCase()
    ] ??
    null
  );
};
